// Lit doors keep glowing while they animate: a sprite holding only the lit pixels of each frame (and the lit
// room behind the door) is drawn over the animating door. Like the tileset colors under it, its palette is the
// day palette mixed with the night one by the time of day, with every color flagged as a light, so the normal
// time blend lights it at dusk, night and morning; at full day it shows exactly the door's own colors.
// Generated by tech/lighting/doors.py.
struct DoorNightOverlay
{
    u16 metatileNum;
    const struct Tileset *secondaryTileset; // NULL: any (primary door metatiles)
    const u32 *tiles;                       // per animation frame: 8 tiles (16x32), Kanto small doors 4 (16x16)
    const u16 *dayPalette;                  // colors | RGB_ALPHA (light flag)
    const u16 *nightPalette;
    u8 numFrames;
};

#include "data/door_night_overlays.h"

// Lit copies of primary door metatiles, made in secondary tilesets so their glass can glow at night
// (tech/lighting/doorglass.py). A copy uses the original door's animation and night overlay.
struct LitDoorCopy
{
    const struct Tileset *secondaryTileset;
    u16 copy;
    u16 original;
};

