// Writes a name with what its game leaves after it: the Japanese games a terminator and then zeros,
// the others terminators (PKHeX checks this).
static void SetMonName(struct Pokemon *mon, s32 field, const u8 *name, u32 length, u8 language)
{
    u8 buffer[POKEMON_NAME_LENGTH + 1];
    u32 i;

    memset(buffer, (language == LANGUAGE_JAPANESE) ? 0 : EOS, sizeof(buffer));
    for (i = 0; i < length && name[i] != EOS; i++)
        buffer[i] = name[i];
    if (i < length)
        buffer[i] = EOS;
    SetMonData(mon, field, buffer);
}

static void SetMonPidIvs(struct Pokemon *mon, const struct PidIvPair *pair)
{
    u32 value;

    ChangeMonPersonality(mon, pair->pid);
    value = pair->iv1 & 0x1F;
    SetMonData(mon, MON_DATA_HP_IV, &value);
    value = (pair->iv1 >> 5) & 0x1F;
    SetMonData(mon, MON_DATA_ATK_IV, &value);
    value = (pair->iv1 >> 10) & 0x1F;
    SetMonData(mon, MON_DATA_DEF_IV, &value);
    value = pair->iv2 & 0x1F;
    SetMonData(mon, MON_DATA_SPEED_IV, &value);
    value = (pair->iv2 >> 5) & 0x1F;
    SetMonData(mon, MON_DATA_SPATK_IV, &value);
    value = (pair->iv2 >> 10) & 0x1F;
    SetMonData(mon, MON_DATA_SPDEF_IV, &value);
    CalculateMonStats(mon);
}

