static void ApplyPidEdit(struct PidTarget *target, u8 *ivs, const struct PidEdit *edit)
{
    switch (edit->type)
    {
    case PID_EDIT_NATURE:
        target->nature = edit->value;
        break;
    case PID_EDIT_GENDER:
        target->gender = edit->value;
        break;
    case PID_EDIT_ABILITY:
        target->abilityNum = edit->value;
        break;
    case PID_EDIT_IV:
        ivs[edit->stat] = edit->value;
        break;
    }
}

