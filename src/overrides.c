#define FLYREGION_ANY 0xFF

// Met data override flags
#define OVERRIDE_NATIONAL_RIBBON (1 << 0) // gets the National Ribbon (a purified Shadow Pokemon has it)
#define OVERRIDE_MALE_TRAINER    (1 << 1) // its trainer is recorded as male, whatever the player is

// A trainer other than the player for a met data override's Pokemon. The secret ID is 0.
struct OverrideTrainer
{
    u8 name[PLAYER_NAME_LENGTH + 1];
    u16 id;
    u8 gender;           // MALE or FEMALE
    bool8 ifNameTooLong; // only used if the player's name is too long for the override's .language
    bool8 shinySecretId; // a shiny Pokemon gets the secret ID that makes its new PID shiny
};

struct MetDataOverride
{
    u16 species;
    u16 map;         // MAP_*
    u8 region;       // FLYREGION_*
    u8 ivPool;       // IV_POOL_*
    u8 metGame;      // VERSION_*, 0 = keep the game's own
    u8 metLocation;  // met location that isn't a map here, instead of .map
    u8 language;     // LANGUAGE_*, 0 = keep the game's own
    u8 flags;        // OVERRIDE_*
    u16 ball;        // ITEM_*, 0 = keep the ball it was caught in
    const u8 *nickname;
    const struct OverrideTrainer *trainer;
    u16 moves[MAX_MON_MOVES];
};

struct PidIvPair
{
    u32 pid;
    u16 iv1; // HP | Atk << 5 | Def << 10
    u16 iv2; // Speed | SpAtk << 5 | SpDef << 10
};

struct IvPool
{
    const struct PidIvPair *pairs;
    u16 count;
};

#define IV_POOL(pairs) {pairs, ARRAY_COUNT(pairs)}

// An encounter slot of a met data override's species on its map in the vanilla game: the slot is
// picked when the encounter slot roll (rand % 100) is in esvMin-esvMax.
struct LegalSlot
{
    u8 esvMin;
    u8 esvMax;
    u8 levelMin;
    u8 levelMax;
};

#define METHOD_BIT(method) (1 << (method))
// Besides Method 1, 2 and 4: Colosseum's, on the GameCube RNG (IVs, ability, then the PID).
#define METHOD_CXD 5

// Generated by tech/override_ivs.py. levels has every level the species' slots on the map can have,
// or the one level of its stationary encounter there. Bit n of masks[i] is set when pair i of the IV
// pool is legal (in PKHeX) for the species met on the map at met level levels[n].
struct LegalIvTable
{
    u16 species;
    u16 map;
    u8 metLocation;
    u8 ivPool;
    u8 metGame;
    const u8 *levels;
    u8 levelCount;
    const u32 *masks;
    const struct LegalSlot *slots; // wild Pokemon: for checking PID/IVs that aren't in the pool
    u8 slotCount;
    u8 freeMethods; // stationary Pokemon: METHOD_BIT()s of the methods any PID/IVs are legal with
    bool8 fateful;  // stationary Pokemon: it has the fateful encounter flag
};

// Custom IV sets for specific species
// Format: HP, ATK, DEF, SPATK, SPDEF, SPD
struct SpeciesCustomIVs
{
    u16 species;
    u8 ivSetCount;  // 1-5
    u8 ivSets[5][6];
};

