void GiveOddEgg(void)
{
    u32 speciesIdx = Random() % ARRAY_COUNT(sWishEggSpecies);
    u16 species = sWishEggSpecies[speciesIdx];
    const struct PidIvPair *entry = &sWishEggPidIvs[Random() % ARRAY_COUNT(sWishEggPidIvs)];
    struct Pokemon mon;
    u8 isEgg;
    u8 metLevel;
    u16 ball;
    u8 language;
    u8 metLocation;
    u16 move;
    u8 pp;
    u8 i;

    CreateMon(&mon, species, EGG_HATCH_LEVEL, 0, TRUE, entry->pid, OT_ID_PLAYER_ID, 0);
    SetMonPidIvs(&mon, entry);

    // Overwrite moves with PCNY Wish Egg event moves
    for (i = 0; i < MAX_MON_MOVES; i++)
    {
        move = (i < ARRAY_COUNT(sWishEggMoves[speciesIdx])) ? sWishEggMoves[speciesIdx][i] : MOVE_NONE;
        pp = (move != MOVE_NONE) ? gBattleMoves[move].pp : 0;
        SetMonData(&mon, MON_DATA_MOVE1 + i, &move);
        SetMonData(&mon, MON_DATA_PP1 + i, &pp);
    }

    // Set egg properties (replicating CreateEgg)
    metLevel = 0;
    ball = ITEM_POKE_BALL;
    language = LANGUAGE_JAPANESE;
    metLocation = METLOC_SPECIAL_EGG;
    isEgg = TRUE;
    SetMonData(&mon, MON_DATA_POKEBALL, &ball);
    SetMonData(&mon, MON_DATA_NICKNAME, sJPEggNickname);
    SetMonData(&mon, MON_DATA_FRIENDSHIP, &gSpeciesInfo[species].eggCycles);
    SetMonData(&mon, MON_DATA_MET_LEVEL, &metLevel);
    SetMonData(&mon, MON_DATA_LANGUAGE, &language);
    SetMonData(&mon, MON_DATA_MET_LOCATION, &metLocation);
    SetMonData(&mon, MON_DATA_MODERN_FATEFUL_ENCOUNTER, &isEgg); // reuse TRUE
    SetMonData(&mon, MON_DATA_IS_EGG, &isEgg);

    if (GetMonData(&gEggSlot, MON_DATA_SPECIES) == SPECIES_NONE)
        gEggSlot = mon;
    else if (GiveMonToPlayer(&mon) == MON_CANT_GIVE)
        return;
    UpdateChain(species);
}

// ---------------------------------------------------------------------------
// Giving a Pokemon a new PID (Mint Master, gender switcher, ability pill and IV changer)
//
// Hatched Pokemon can have any PID (PKHeX accepts any nonzero PID for Gen 3 eggs), so a random one
// with the wanted nature, gender, ability and shininess is used. Wish egg and IV pool Pokemon got
// their PID and IVs from the same RNG calls, so their PID has to be one the RNG makes right before
// their IVs: PokeFinder's IV seed recovery finds those few PIDs. For wild IV pool Pokemon the met
// level also has to be one PKHeX finds the PID's encounter slot and level rolls for; for stationary
// ones the PID has to be of a method PKHeX accepts for the encounter.

#define RNG_NEXT(seed) ((seed) * 0x41C64E6D + 0x6073)
#define RNG_PREV(seed) ((seed) * 0xEEB9EB65 + 0x0A3561A1)
// The GameCube games' RNG
#define XD_NEXT(seed) ((seed) * 0x000343FD + 0x00269EC3)
#define XD_PREV(seed) ((seed) * 0xB9B33155 + 0xA170F641)
#define XD_PREV_1000(seed) ((seed) * 0x251CC8E1 + 0x94750758)
#define COLOR_BITS(pid) (((pid) >> 16) & 0x3F)

#define MAX_IV_SEEDS 12

enum
{
    PID_KIND_FREE,      // any PID is legal: hatched, or a Pokemon whose PID correlation isn't handled here
    PID_KIND_WISH_EGG,  // Method 2 PID/IVs
    PID_KIND_MET_OVERRIDE, // met on a met data override's map with an IV pool: Method 1/2/4 PID/IVs that PKHeX
                           // traces to its encounter slots there, or PID/IVs of a method it accepts for its
                           // stationary or Colosseum encounter
};

struct PidTarget
{
    u32 otId;
    u16 species;
    u8 nature;
    u8 gender;
    u8 abilityNum;
    bool8 isShiny;
};

// Best candidate so far: lowest tier wins, ties are picked from at random.
struct PidChoice
{
    u32 pid;
    u16 count;
    u8 metLevel;
    u8 tier;
};

void GetMonIVs(struct Pokemon *mon, u8 *ivs)
{
    u32 i;

    for (i = 0; i < NUM_STATS; i++)
        ivs[i] = GetMonData(mon, MON_DATA_HP_IV + i, NULL);
}

static void SetMonIVs(struct Pokemon *mon, const u8 *ivs)
{
    u32 i;

    for (i = 0; i < NUM_STATS; i++)
        SetMonData(mon, MON_DATA_HP_IV + i, &ivs[i]);
}

static bool32 HasTwoAbilities(u16 species)
{
    return gSpeciesInfo[species].abilities[1] != ABILITY_NONE;
}

// Same rule as CreateBoxMon: the ability follows the PID only for two-ability species.
static void SetMonPidAbility(struct Pokemon *mon, u16 species, u32 pid)
{
    u8 abilityNum = HasTwoAbilities(species) ? (pid & 1) : 0;

    SetMonData(mon, MON_DATA_ABILITY_NUM, &abilityNum);
}

static bool32 IsPidMatch(const struct PidTarget *target, u32 pid)
{
    if (pid == 0 || pid % NUM_NATURES != target->nature)
        return FALSE;
    if (GetGenderFromSpeciesAndPersonality(target->species, pid) != target->gender)
        return FALSE;
    if (HasTwoAbilities(target->species) && (pid & 1) != target->abilityNum)
        return FALSE;
    return IsShinyOtIdPersonality(target->otId, pid) == target->isShiny;
}

static void ConsiderPid(struct PidChoice *best, u32 pid, u8 metLevel, u8 tier)
{
    if (tier > best->tier)
        return;
    if (tier < best->tier)
    {
        best->tier = tier;
        best->count = 0;
    }
    best->count++;
    if (Random() % best->count == 0)
    {
        best->pid = pid;
        best->metLevel = metLevel;
    }
}

static u32 AddIvSeed(u32 *seeds, u32 count, u32 seed)
{
    u32 i;

    for (i = 0; i < count; i++)
    {
        if (seeds[i] == seed)
            return count;
    }
    if (count < MAX_IV_SEEDS)
        seeds[count++] = seed;
    return count;
}

// PokeFinder's recoverPokeRNGIVMethod12 (Core/RNG/LCRNGReverse.cpp): the RNG states whose top half
// gives iv1 (bit 15 is unused) and whose next call gives iv2.
static u32 RecoverIvSeedsNoGap(u32 iv1, u32 iv2, u32 *seeds)
{
    u32 first = iv1 << 16, second = iv2 << 16;
    u32 tmp = ((second - 0x41C64E6D * first) >> 16) * 0xC907;
    u32 starts[3];
    u32 i, lbits, seed, count = 0;

    starts[0] = ((tmp + 0x3443) >> 15) * 0x67D3;
    starts[1] = starts[0] + 0x67D3;
    starts[2] = ((tmp + 0xC34E) >> 15) * 0x67D3;
    for (i = 0; i < ARRAY_COUNT(starts); i++)
    {
        if (i == 2 && starts[2] == starts[1])
            break;
        for (lbits = starts[i] % 0xC907; lbits < 0x10000; lbits += 0xC907)
        {
            seed = first | lbits;
            if ((RNG_NEXT(seed) & 0x7FFF0000) == second)
            {
                count = AddIvSeed(seeds, count, seed);
                count = AddIvSeed(seeds, count, seed ^ 0x80000000);
            }
        }
    }
    return count;
}

// PokeFinder's recoverPokeRNGIVMethod4: the RNG states whose top half gives iv1 and whose second
// next call gives iv2.
static u32 RecoverIvSeedsGap(u32 iv1, u32 iv2, u32 *seeds)
{
    u32 first = iv1 << 16, second = iv2 << 16;
    u32 tmp = ((first - second * (0xEEB9EB65 * 0xEEB9EB65)) >> 16) * 0x6C31;
    u32 bounds[2];
    u32 i, lbits, seed, count = 0;

    bounds[0] = (tmp + 0x1574621D) >> 15;
    bounds[1] = (tmp + 0x157488D6) >> 15;
    for (i = 0; i < ARRAY_COUNT(bounds); i++)
    {
        if (i == 1 && bounds[1] == bounds[0])
            break;
        for (lbits = (bounds[i] * 0x2E90) % 0x6C31; lbits < 0x10000; lbits += 0x6C31)
        {
            seed = RNG_PREV(RNG_PREV(second | lbits));
            if ((seed & 0x7FFF0000) == first)
            {
                count = AddIvSeed(seeds, count, seed);
                count = AddIvSeed(seeds, count, seed ^ 0x80000000);
            }
        }
    }
    return count;
}

// PKHeX's XDRNG.GetSeedsIVs: the GameCube RNG states whose top half gives iv1 (bit 15 is unused) and
// whose next call gives iv2.
static u32 RecoverXdIvSeeds(u32 iv1, u32 iv2, u32 *seeds)
{
    u32 first = iv1 << 16, second = iv2 << 16;
    u32 tmp = ((0xB9B33155 * second - first) >> 16) * 0xE8D1;
    u32 starts[3];
    u32 i, low, seed, sum, count = 0;

    // The sums are 33 bits wide.
    sum = tmp + 0x1E694393;
    starts[0] = ((sum >> 15) | ((sum < tmp) << 17)) * 0x44C5;
    starts[1] = starts[0] + 0x44C5;
    sum = tmp + 0x1E69FAC8;
    starts[2] = ((sum >> 15) | ((sum < tmp) << 17)) * 0x44C5;
    for (i = 0; i < ARRAY_COUNT(starts); i++)
    {
        if (i == 2 && starts[2] == starts[1])
            break;
        for (low = starts[i] % 0xE8D1; low < 0x10000; low += 0xE8D1)
        {
            seed = XD_PREV(second | low);
            if ((seed & 0x7FFF0000) == first)
            {
                count = AddIvSeed(seeds, count, seed);
                count = AddIvSeed(seeds, count, seed ^ 0x80000000);
            }
        }
    }
    return count;
}

// The PID Colosseum makes after the IVs of ivSeed (the state whose top half is IV1): IV2, a call for
// the ability, then the PID's high and low halves.
static u32 GetXdPid(u32 ivSeed)
{
    u32 high = XD_NEXT(XD_NEXT(XD_NEXT(ivSeed)));

    return (high & 0xFFFF0000) | (XD_NEXT(high) >> 16);
}

static bool32 IsColosseumNameScreenSeed(u32 seed)
{
    bool32 p1, p2, p3, p4;

    p1 = (seed >> 16) > 0x1999;
    seed = XD_PREV(seed);
    p2 = (seed >> 16) > 0x1999;
    seed = XD_PREV(seed);
    p3 = (seed >> 16) > 0x1999;
    seed = XD_PREV(seed);
    p4 = (seed >> 16) > 0x1999;
    if (p1 && p2 && p3 && p4)
        return TRUE;

    seed = XD_PREV(seed);
    if ((seed >> 16) <= 0x1999 && IsColosseumNameScreenSeed(XD_PREV(seed)))
        return TRUE;
    seed = XD_PREV(seed);
    if ((seed >> 16) <= 0x1999 && p1 && IsColosseumNameScreenSeed(XD_PREV(seed)))
        return TRUE;
    seed = XD_PREV(seed);
    if ((seed >> 16) <= 0x1999 && p1 && p2 && IsColosseumNameScreenSeed(XD_PREV(seed)))
        return TRUE;
    seed = XD_PREV(seed);
    if ((seed >> 16) <= 0x1999 && p1 && p2 && p3 && IsColosseumNameScreenSeed(XD_PREV(seed)))
        return TRUE;
    return FALSE;
}

// PKHeX's MethodCXD.TryGetSeedTrainerID: whether Colosseum can give a new game the trainer ID and
// secret ID. They are two consecutive RNG calls, 1000 calls after the name was confirmed, which can
// only happen on some RNG states (the name screen draws from the RNG every frame).
bool32 IsColosseumTrainerId(u16 trainerId, u16 secretId)
{
    u32 first = trainerId << 16, second = secretId << 16;
    u32 tmp = ((first - second * 0xB9B33155) >> 16) * 0xE8D1;
    u32 bounds[2];
    u32 i, low, seed, sum;

    // The sums are 33 bits wide.
    sum = tmp + 0x55FF8537;
    bounds[0] = (sum >> 16) | ((sum < tmp) << 16);
    sum = tmp + 0x55FFBC6C;
    bounds[1] = (sum >> 16) | ((sum < tmp) << 16);
    for (i = 0; i < ARRAY_COUNT(bounds); i++)
    {
        if (i == 1 && bounds[1] == bounds[0])
            break;
        for (low = (bounds[i] * 0x5F47) % 0xE8D1; low < 0x10000; low += 0xE8D1)
        {
            seed = XD_PREV(second | low);
            if ((seed & 0xFFFF0000) == first && IsColosseumNameScreenSeed(XD_PREV_1000(XD_PREV(seed))))
                return TRUE;
        }
    }
    return FALSE;
}

// The PID that Method 1, 2 or 4 makes before the IVs of ivSeed (the state whose top half is IV1):
// two calls (low half first) right before the IVs, or before a skipped call for Method 2.
// *pidSeed is set to the RNG state right before the PID's first call.
static u32 GetMethodPid(u32 ivSeed, u8 method, u32 *pidSeed)
{
    u32 high = RNG_PREV(ivSeed);
    u32 low;

    if (method == 2)
        high = RNG_PREV(high);
    low = RNG_PREV(high);
    *pidSeed = RNG_PREV(low);
    return (high & 0xFFFF0000) | (low >> 16);
}

static u32 GetLevelBit(const struct LegalIvTable *table, u32 level)
{
    u32 i;

    for (i = 0; i < table->levelCount; i++)
    {
        if (table->levels[i] == level)
            return 1u << i;
    }
    return 0;
}

// PKHeX's Method H check (MethodH.GetOriginSeedEmerald), for no lead and Synchronize only, so
// anything it accepts PKHeX accepts too. The wild Pokemon generation rolls the encounter slot, the
// level and the nature (or the Synchronize check), then PIDs until one has that nature. Walking back
// from the PID past rerolled PIDs, each earlier call could have been the nature roll until two calls
// that would have made a PID with the nature already. Returns the table's level bits of the met
// levels that are legal. pidSeed is the RNG state right before the PID's first call.
static u32 GetMethodHLegalLevels(const struct LegalIvTable *table, u32 pidSeed, u32 pid)
{
    u32 nature = pid % NUM_NATURES;
    bool32 sync = (table->metGame == 0 || table->metGame == VERSION_EMERALD);
    u32 seed = pidSeed, levelSeed, roll, esv, mask = 0, i, steps;

    for (steps = 0; steps < 1000; steps++)
    {
        roll = seed >> 16;
        if (roll % NUM_NATURES == nature || (sync && !(roll & 1)))
        {
            levelSeed = RNG_PREV(seed);
            esv = (RNG_PREV(levelSeed) >> 16) % 100;
            for (i = 0; i < table->slotCount; i++)
            {
                const struct LegalSlot *slot = &table->slots[i];

                if (esv >= slot->esvMin && esv <= slot->esvMax)
                    mask |= GetLevelBit(table, slot->levelMin + (levelSeed >> 16) % (slot->levelMax - slot->levelMin + 1));
            }
        }
        if (((roll << 16) | (RNG_PREV(seed) >> 16)) % NUM_NATURES == nature)
            break;
        seed = RNG_PREV(RNG_PREV(seed));
    }
    return mask;
}

// The met level bits PKHeX accepts for the pair, which is of the method: every level if the
// (stationary) encounter takes any PID/IVs of the method, else from the generated table if the pair
// is in the pool, and from the game's own Method H check.
static u32 GetLegalMetLevels(const struct LegalIvTable *table, u8 method, u32 pid, u32 pidSeed, u16 iv1, u16 iv2)
{
    const struct IvPool *pool = &sIvPools[table->ivPool];
    u32 mask = 0, i;

    if (table->freeMethods & METHOD_BIT(method))
        return (1u << table->levelCount) - 1;

    for (i = 0; i < pool->count; i++)
    {
        if (pool->pairs[i].pid == pid && pool->pairs[i].iv1 == iv1 && pool->pairs[i].iv2 == iv2)
        {
            mask = table->masks[i];
            break;
        }
    }
    if (table->slotCount != 0)
        mask |= GetMethodHLegalLevels(table, pidSeed, pid);
    return mask;
}

static bool32 IsWishEggFamily(u16 species)
{
    u32 i;
    u16 base = GetEggSpecies(species);

    for (i = 0; i < ARRAY_COUNT(sWishEggSpecies); i++)
    {
        if (GetEggSpecies(sWishEggSpecies[i]) == base)
            return TRUE;
    }
    return FALSE;
}

static u8 GetPidKind(struct Pokemon *mon, const struct LegalIvTable **legalTable)
{
    u16 species = GetMonData(mon, MON_DATA_SPECIES, NULL);
    u8 metLevel = GetMonData(mon, MON_DATA_MET_LEVEL, NULL);
    u8 metLocation = GetMonData(mon, MON_DATA_MET_LOCATION, NULL);
    u8 metGame = GetMonData(mon, MON_DATA_MET_GAME, NULL);
    u32 i;

    if (metLevel == 0)
    {
        if (GetMonData(mon, MON_DATA_MODERN_FATEFUL_ENCOUNTER, NULL) && IsWishEggFamily(species))
            return PID_KIND_WISH_EGG;
        return PID_KIND_FREE;
    }

    for (i = 0; i < ARRAY_COUNT(sLegalIvTables); i++)
    {
        const struct LegalIvTable *table = &sLegalIvTables[i];

        if (table->species != species || (table->metGame != 0 ? table->metGame : gGameVersion) != metGame)
            continue;
        if (GetMapOrMetLocation(table->map, table->metLocation) != metLocation)
            continue;
        *legalTable = table;
        return PID_KIND_MET_OVERRIDE;
    }
    return PID_KIND_FREE;
}

// Any PID is legal: try random ones, keeping the color variation bits if possible.
static u8 TryChangeFreePid(struct Pokemon *mon, const struct PidTarget *target)
{
    u32 colorBits = COLOR_BITS(GetMonData(mon, MON_DATA_PERSONALITY, NULL));
    u32 shinyXor = (target->otId & 0xFFFF) ^ (target->otId >> 16);
    u32 pid, tries;
    bool32 keepColor;

    for (keepColor = TRUE; ; keepColor = FALSE)
    {
        for (tries = 0; tries < 0x8000; tries++)
        {
            pid = Random32();
            if (target->isShiny)
                pid = ((((pid & 0xFFFF) ^ shinyXor ^ (Random() & 7)) & 0xFFFF) << 16) | (pid & 0xFFFF);
            if (keepColor)
                pid = (pid & ~(0x3Fu << 16)) | (colorBits << 16);
            if (IsPidMatch(target, pid))
            {
                ChangeMonPersonality(mon, pid);
                SetMonPidAbility(mon, target->species, pid);
                return keepColor ? PID_CHANGE_DONE : PID_CHANGE_DONE_NEW_COLOR;
            }
        }
        if (!keepColor)
            return PID_CHANGE_NO_LEGAL_PID;
    }
}

// The PID has to come right before the IVs in the RNG. Candidates are ranked by keeping the color
// variation, then (IV pool Pokemon) keeping the met level, then a lower one, then a higher one
// no higher than the Pokemon's level. With firstIsEnough it stops at the first legal one.
static bool32 FindLinkedPid(struct Pokemon *mon, const struct PidTarget *target, const u8 *ivs, u8 kind,
                            const struct LegalIvTable *table, struct PidChoice *best, bool32 firstIsEnough)
{
    static const u8 sOverrideMethods[] = {1, 2, 4, METHOD_CXD};
    static const u8 sWishEggMethods[] = {2};
    const u8 *methods = (kind == PID_KIND_WISH_EGG) ? sWishEggMethods : sOverrideMethods;
    u32 methodCount = (kind == PID_KIND_WISH_EGG) ? ARRAY_COUNT(sWishEggMethods) : ARRAY_COUNT(sOverrideMethods);
    u16 iv1 = ivs[STAT_HP] | (ivs[STAT_ATK] << 5) | (ivs[STAT_DEF] << 10);
    u16 iv2 = ivs[STAT_SPEED] | (ivs[STAT_SPATK] << 5) | (ivs[STAT_SPDEF] << 10);
    u32 colorBits = COLOR_BITS(GetMonData(mon, MON_DATA_PERSONALITY, NULL));
    u8 level = GetMonData(mon, MON_DATA_LEVEL, NULL);
    u8 metLevel = GetMonData(mon, MON_DATA_MET_LEVEL, NULL);
    u32 seeds[MAX_IV_SEEDS];
    u32 m, i, bit, seedCount, pid, pidSeed, levels, colorTier, levelTier;
    u8 lv;

    best->tier = 0xFF;
    best->count = 0;
    for (m = 0; m < methodCount; m++)
    {
        // A stationary encounter only takes some methods; a wild one never Colosseum's.
        if (kind == PID_KIND_MET_OVERRIDE && (table->slotCount == 0 || methods[m] == METHOD_CXD)
         && !(table->freeMethods & METHOD_BIT(methods[m])))
            continue;

        if (methods[m] == METHOD_CXD)
            seedCount = RecoverXdIvSeeds(iv1, iv2, seeds);
        else if (methods[m] == 4)
            seedCount = RecoverIvSeedsGap(iv1, iv2, seeds);
        else
            seedCount = RecoverIvSeedsNoGap(iv1, iv2, seeds);

        for (i = 0; i < seedCount; i++)
        {
            pidSeed = 0;
            if (methods[m] == METHOD_CXD)
                pid = GetXdPid(seeds[i]);
            else
                pid = GetMethodPid(seeds[i], methods[m], &pidSeed);
            if (!IsPidMatch(target, pid))
                continue;
            colorTier = (COLOR_BITS(pid) == colorBits) ? 0 : 1;
            if (kind == PID_KIND_WISH_EGG)
            {
                ConsiderPid(best, pid, metLevel, colorTier * 3);
            }
            else
            {
                levels = GetLegalMetLevels(table, methods[m], pid, pidSeed, iv1, iv2);
                for (bit = 0; bit < table->levelCount; bit++)
                {
                    lv = table->levels[bit];
                    if (!(levels & (1u << bit)) || lv > level)
                        continue;
                    if (lv == metLevel)
                        levelTier = 0;
                    else if (lv < metLevel)
                        levelTier = 1;
                    else
                        levelTier = 2;
                    ConsiderPid(best, pid, lv, colorTier * 3 + levelTier);
                }
            }
            if (firstIsEnough && best->tier != 0xFF)
                return TRUE;
        }
    }
    return best->tier != 0xFF;
}

static void InitPidTarget(struct PidTarget *target, struct Pokemon *mon, u8 nature, u8 gender, u8 abilityNum)
{
    target->otId = GetMonData(mon, MON_DATA_OT_ID, NULL);
    target->species = GetMonData(mon, MON_DATA_SPECIES, NULL);
    target->nature = nature;
    target->gender = gender;
    target->abilityNum = abilityNum;
    target->isShiny = IsMonShiny(mon);
}

// Gives the Pokemon a legal PID with the given nature, gender and ability number, and the given IVs
// (indexed by STAT_*), keeping its shininess and if possible its color variation. Flags:
//   PID_CHANGE_FLAG_TOGGLE_SHINY  flip shininess (only for Pokemon whose PID isn't tied to their IVs)
//   PID_CHANGE_FLAG_FORCE         skip the legality check: any PID with the change, as for hatched Pokemon
// Returns PID_CHANGE_*; on PID_CHANGE_NO_LEGAL_PID nothing changed.
u8 TryChangeMonPid(struct Pokemon *mon, u8 nature, u8 gender, u8 abilityNum, const u8 *ivs, u8 flags)
{
    const struct LegalIvTable *table = NULL;
    u8 kind = GetPidKind(mon, &table);
    struct PidTarget target;
    struct PidChoice best;
    u8 result;

    InitPidTarget(&target, mon, nature, gender, abilityNum);
    if (flags & PID_CHANGE_FLAG_FORCE)
        kind = PID_KIND_FREE;

    if (kind == PID_KIND_FREE)
    {
        if (flags & PID_CHANGE_FLAG_TOGGLE_SHINY)
            target.isShiny = !target.isShiny;
        if (IsPidMatch(&target, GetMonData(mon, MON_DATA_PERSONALITY, NULL)))
            result = PID_CHANGE_DONE; // IVs only
        else
            result = TryChangeFreePid(mon, &target);
        if (result != PID_CHANGE_NO_LEGAL_PID)
            SetMonIVs(mon, ivs);
    }
    else if (FindLinkedPid(mon, &target, ivs, kind, table, &best, FALSE))
    {
        ChangeMonPersonality(mon, best.pid);
        SetMonPidAbility(mon, target.species, best.pid);
        SetMonIVs(mon, ivs);
        if (kind == PID_KIND_MET_OVERRIDE)
            SetMonData(mon, MON_DATA_MET_LEVEL, &best.metLevel);
        result = (best.tier < 3) ? PID_CHANGE_DONE : PID_CHANGE_DONE_NEW_COLOR;
    }
    else
    {
        result = PID_CHANGE_NO_LEGAL_PID;
    }

    if (result != PID_CHANGE_NO_LEGAL_PID)
        CalculateMonStats(mon);
    return result;
}

