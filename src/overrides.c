struct MetDataOverride
{
    u16 species;
    u16 map;    // MAP_*
    u8 region;  // FLYREGION_*
    u8 ivPool;  // IV_POOL_*
    u8 metGame; // VERSION_*, 0 = keep the game's own
};

struct PidIvPair
{
    u32 pid;
    u16 iv1; // HP | Atk << 5 | Def << 10
    u16 iv2; // Speed | SpAtk << 5 | SpDef << 10
};

struct IvPool
{
    const struct PidIvPair *pairs;
    u16 count;
};

#define IV_POOL(pairs) {pairs, ARRAY_COUNT(pairs)}

// Generated by tech/override_ivs.py. Bit n of masks[i] is set when pair i of the IV pool is legal
// (in PKHeX) for the species met on the map at met level levels[n].
struct LegalIvTable
{
    u16 species;
    u16 map;
    u8 ivPool;
    u8 metGame;
    const u8 *levels;
    u8 levelCount;
    const u32 *masks;
};

// Custom IV sets for specific species
// Format: HP, ATK, DEF, SPATK, SPDEF, SPD
struct SpeciesCustomIVs
{
    u16 species;
    u8 ivSetCount;  // 1-5
    u8 ivSets[5][6];
};

