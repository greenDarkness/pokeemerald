static bool32 IsCaughtAsHatched(u16 species)
{
    u32 i;

    if (gSpeciesInfo[species].eggGroups[0] != EGG_GROUP_NO_EGGS_DISCOVERED
     && gSpeciesInfo[species].eggGroups[0] != EGG_GROUP_DITTO)
        return TRUE;

    for (i = 0; i < ARRAY_COUNT(sCaughtAsHatchedSpecies); i++)
    {
        if (sCaughtAsHatchedSpecies[i] == species)
            return TRUE;
    }
    return FALSE;
}

static const struct WildPokemonHeader *GetWildMonHeaderForMap(u8 mapGroup, u8 mapNum)
{
    u32 i;

    for (i = 0; gWildMonHeaders[i].mapGroup != MAP_GROUP(MAP_UNDEFINED); i++)
    {
        if (gWildMonHeaders[i].mapGroup == mapGroup && gWildMonHeaders[i].mapNum == mapNum)
            return &gWildMonHeaders[i];
    }
    return NULL;
}

// Picks a random level that one of the map's wild encounter slots for the species could have
// had, no higher than maxLevel. Returns 0 if there is none.
static u8 ChooseLegalMetLevel(const struct WildPokemonHeader *header, u16 species, u8 maxLevel)
{
    static const u8 sSlotCounts[] = {
        NUM_LAND_MONS_ENCOUNTER_SLOTS, NUM_WATER_MONS_ENCOUNTER_SLOTS,
        NUM_ROCK_SMASH_MONS_ENCOUNTER_SLOTS, NUM_FISHING_MONS_ENCOUNTER_SLOTS,
    };
    const struct WildPokemonInfo *infos[] = {
        header->landMonsInfo, header->waterMonsInfo, header->rockSmashMonsInfo, header->fishingMonsInfo,
    };
    const struct WildPokemon *legalSlots[NUM_LAND_MONS_ENCOUNTER_SLOTS + NUM_WATER_MONS_ENCOUNTER_SLOTS
                                         + NUM_ROCK_SMASH_MONS_ENCOUNTER_SLOTS + NUM_FISHING_MONS_ENCOUNTER_SLOTS];
    const struct WildPokemon *slot;
    u32 i, j, count = 0;

    for (i = 0; i < ARRAY_COUNT(infos); i++)
    {
        if (infos[i] == NULL)
            continue;
        for (j = 0; j < sSlotCounts[i]; j++)
        {
            slot = &infos[i]->wildPokemon[j];
            if (slot->species == species && slot->minLevel <= maxLevel)
                legalSlots[count++] = slot;
        }
    }
    if (count == 0)
        return 0;

    slot = legalSlots[Random() % count];
    return slot->minLevel + Random() % (min(slot->maxLevel, maxLevel) - slot->minLevel + 1);
}

static const struct LegalIvTable *GetLegalIvTable(const struct MetDataOverride *override)
{
    u32 i;

    for (i = 0; i < ARRAY_COUNT(sLegalIvTables); i++)
    {
        const struct LegalIvTable *table = &sLegalIvTables[i];

        if (table->species == override->species && table->map == override->map
         && table->metLocation == override->metLocation
         && table->ivPool == override->ivPool && table->metGame == override->metGame)
            return table;
    }
    return NULL;
}

static metloc_u8_t GetMapOrMetLocation(u16 map, u8 metLocation)
{
    if (metLocation != 0)
        return metLocation;
    return Overworld_GetMapHeaderByGroupAndId(MAP_GROUP(map), MAP_NUM(map))->regionMapSectionId;
}

// The override's trainer if the Pokemon gets it, else NULL (it stays the player's).
static const struct OverrideTrainer *GetOverrideTrainer(const struct MetDataOverride *override)
{
    const struct OverrideTrainer *trainer = override->trainer;
    u32 maxLength = (override->language == LANGUAGE_JAPANESE) ? 5 : PLAYER_NAME_LENGTH;

    if (trainer != NULL && trainer->ifNameTooLong && StringLength(gSaveBlock2Ptr->playerName) <= maxLength)
        return NULL;
    return trainer;
}

struct IvPoolFilter
{
    u32 levelMask; // usable bits of the legal table's masks (levels no higher than the Pokemon's)
    u32 otId;      // of the trainer it will have
    u32 colorBits;
    u16 species;
    u8 gender;
    bool8 isShiny;
    bool8 anyShininess; // its new trainer gets the secret ID that makes whichever PID shiny
    bool8 keepColor;
};

static u32 CountSetBits(u32 mask)
{
    u32 count = 0;

    while (mask != 0)
    {
        mask &= mask - 1;
        count++;
    }
    return count;
}

// Returns the legal table bits of the met levels the pair can be used with.
static u32 GetUsableMetLevels(const struct IvPoolFilter *filter, const struct LegalIvTable *table, const struct IvPool *pool, u32 index)
{
    u32 pid = pool->pairs[index].pid;

    if (!filter->anyShininess && IsShinyOtIdPersonality(filter->otId, pid) != filter->isShiny)
        return 0;
    if (GetGenderFromSpeciesAndPersonality(filter->species, pid) != filter->gender)
        return 0;
    if (filter->keepColor && ((pid >> 16) & 0x3F) != filter->colorBits)
        return 0;
    return table->masks[index] & filter->levelMask;
}

// Finds what the Pokemon can get of the override's IV pool: pairs legal at its map with a met level
// no higher than its level, that keep its shininess and gender. Prefers its own level as met level
// (else it looks leveled up without battling until it gains EXP), then keeping its color variation
// (personality bits 16-21). Sets up the filter for the best of those and returns how many pair/met
// level choices it leaves (0 = the pool can't be used).
static u32 FindIvPoolChoices(struct Pokemon *mon, const struct MetDataOverride *override, const struct LegalIvTable *table,
                             struct IvPoolFilter *filter)
{
    const struct IvPool *pool = &sIvPools[override->ivPool];
    const struct OverrideTrainer *trainer = GetOverrideTrainer(override);
    u32 i, count, tier;
    u32 lowerMask = 0, sameMask = 0;
    u8 level;

    if (table == NULL)
        return 0;

    level = GetMonData(mon, MON_DATA_LEVEL, NULL);
    for (i = 0; i < table->levelCount; i++)
    {
        if (table->levels[i] == level)
            sameMask |= 1u << i;
        else if (table->levels[i] < level)
            lowerMask |= 1u << i;
    }
    if (sameMask == 0 && lowerMask == 0)
        return 0;

    filter->otId = (trainer != NULL) ? trainer->id : GetMonData(mon, MON_DATA_OT_ID, NULL);
    filter->colorBits = (GetMonData(mon, MON_DATA_PERSONALITY, NULL) >> 16) & 0x3F;
    filter->species = override->species;
    filter->gender = GetMonGender(mon);
    filter->isShiny = IsMonShiny(mon);
    filter->anyShininess = (trainer != NULL && trainer->shinySecretId && filter->isShiny);

    // Tiers, best first: same level and color, same level, lower level and color, any usable level.
    count = 0;
    for (tier = 0; tier < 4 && count == 0; tier++)
    {
        filter->levelMask = (tier < 2) ? sameMask : (sameMask | lowerMask);
        filter->keepColor = (tier % 2 == 0);
        if (filter->levelMask == 0)
            continue;
        for (i = 0; i < pool->count; i++)
            count += CountSetBits(GetUsableMetLevels(filter, table, pool, i));
    }
    return count;
}

// What the override sets besides the PID, IVs and met data: trainer, language, name, ball, ribbon
// and moves.
static void ApplyOverrideDetails(struct Pokemon *mon, const struct MetDataOverride *override, bool32 makeShiny)
{
    const struct OverrideTrainer *trainer = GetOverrideTrainer(override);
    u8 language = (override->language != 0) ? override->language : GetMonData(mon, MON_DATA_LANGUAGE, NULL);
    u32 otId, pid, i;
    u8 value;

    if (trainer != NULL)
    {
        otId = trainer->id;
        if (makeShiny)
        {
            pid = GetMonData(mon, MON_DATA_PERSONALITY, NULL);
            otId |= (trainer->id ^ HIHALF(pid) ^ LOHALF(pid)) << 16;
        }
        ChangeMonOtId(mon, otId);
        SetMonName(mon, MON_DATA_OT_NAME, trainer->name, PLAYER_NAME_LENGTH, language);
        value = trainer->gender;
        SetMonData(mon, MON_DATA_OT_GENDER, &value);
    }
    else if (override->language != 0)
    {
        SetMonName(mon, MON_DATA_OT_NAME, gSaveBlock2Ptr->playerName, PLAYER_NAME_LENGTH, language);
    }
    if (override->flags & OVERRIDE_MALE_TRAINER)
    {
        value = MALE;
        SetMonData(mon, MON_DATA_OT_GENDER, &value);
    }
    if (override->language != 0)
        SetMonData(mon, MON_DATA_LANGUAGE, &override->language);
    if (override->nickname != NULL)
        SetMonName(mon, MON_DATA_NICKNAME, override->nickname, POKEMON_NAME_LENGTH, language);
    if (override->ball != ITEM_NONE)
    {
        value = override->ball;
        SetMonData(mon, MON_DATA_POKEBALL, &value);
    }
    if (override->flags & OVERRIDE_NATIONAL_RIBBON)
    {
        value = TRUE;
        SetMonData(mon, MON_DATA_NATIONAL_RIBBON, &value);
    }
    if (override->moves[0] != MOVE_NONE)
    {
        value = 0;
        SetMonData(mon, MON_DATA_PP_BONUSES, &value);
        for (i = 0; i < MAX_MON_MOVES; i++)
        {
            SetMonData(mon, MON_DATA_MOVE1 + i, &override->moves[i]);
            SetMonData(mon, MON_DATA_PP1 + i, &gBattleMoves[override->moves[i]].pp);
        }
    }
}

// Gives the Pokemon a random pair of the override's IV pool among the best it can get (see
// FindIvPoolChoices) and the override's details. Also sets or clears its fateful encounter flag to
// match the encounter on the map. Returns the met level to use, or 0 if no pair fits.
static u8 TryApplyIvPool(struct Pokemon *mon, const struct MetDataOverride *override)
{
    const struct LegalIvTable *table = GetLegalIvTable(override);
    const struct IvPool *pool = &sIvPools[override->ivPool];
    struct IvPoolFilter filter;
    u32 i, bit, count, levels, pick;
    u8 abilityNum;
    bool8 fateful;

    count = FindIvPoolChoices(mon, override, table, &filter);
    if (count == 0)
        return 0;

    pick = Random32() % count;
    for (i = 0; i < pool->count; i++)
    {
        levels = GetUsableMetLevels(&filter, table, pool, i);
        count = CountSetBits(levels);
        if (pick >= count)
        {
            pick -= count;
            continue;
        }

        for (bit = 0; ; bit++)
        {
            if (!(levels & (1u << bit)))
                continue;
            if (pick == 0)
                break;
            pick--;
        }
        SetMonPidIvs(mon, &pool->pairs[i]);
        // Same rule as CreateBoxMon: the ability follows the PID only for two-ability species.
        abilityNum = (gSpeciesInfo[override->species].abilities[1] != ABILITY_NONE) ? (pool->pairs[i].pid & 1) : 0;
        SetMonData(mon, MON_DATA_ABILITY_NUM, &abilityNum);
        // An event Pokemon (CreateEnemyEventMon) has the flag even if the encounter it's given doesn't.
        fateful = table->fateful;
        SetMonData(mon, MON_DATA_MODERN_FATEFUL_ENCOUNTER, &fateful);
        ApplyOverrideDetails(mon, override, filter.anyShininess);
        return table->levels[bit];
    }
    return 0;
}

static const struct MetDataOverride *GetMetDataOverride(u16 species, metloc_u8_t metLocation)
{
    u32 i;

    for (i = 0; i < ARRAY_COUNT(sMetDataOverrides); i++)
    {
        const struct MetDataOverride *override = &sMetDataOverrides[i];

        if (override->species == species
         && (override->region == FLYREGION_ANY || override->region == GetFlyRegionForMapsec(metLocation)))
            return override;
    }
    return NULL;
}

static void TryApplyMetDataOverride(struct Pokemon *mon, u16 species, metloc_u8_t metLocation)
{
    const struct MetDataOverride *override = GetMetDataOverride(species, metLocation);
    const struct WildPokemonHeader *header;
    metloc_u8_t legalLocation;
    u8 metLevel = 0;

    if (override == NULL)
        return;

    legalLocation = GetMapOrMetLocation(override->map, override->metLocation);
    if (override->ivPool != IV_POOL_NONE)
        metLevel = TryApplyIvPool(mon, override);

    if (metLevel == 0)
    {
        if (legalLocation == metLocation || override->metLocation != 0)
            return;
        header = GetWildMonHeaderForMap(MAP_GROUP(override->map), MAP_NUM(override->map));
        if (header == NULL)
            return;
        metLevel = ChooseLegalMetLevel(header, species, GetMonData(mon, MON_DATA_LEVEL, NULL));
        if (metLevel == 0)
            return;
    }

    SetMonData(mon, MON_DATA_MET_LOCATION, &legalLocation);
    SetMonData(mon, MON_DATA_MET_LEVEL, &metLevel);
    if (override->metGame != 0)
        SetMonData(mon, MON_DATA_MET_GAME, &override->metGame);
}

static bool32 IsCaughtMonMetAt(u16 species)
{
    return (gBattleTypeFlags & BATTLE_TYPE_LEGENDARY) || !IsCaughtAsHatched(species);
}

// Whether the wild Pokemon will be given a name by a met data override once caught, so the player
// isn't asked to name it.
bool8 DoesCaughtMonGetOverrideName(struct Pokemon *mon)
{
    u16 species = GetMonData(mon, MON_DATA_SPECIES, NULL);
    const struct MetDataOverride *override;
    struct IvPoolFilter filter;

    if (!IsCaughtMonMetAt(species))
        return FALSE;
    override = GetMetDataOverride(species, GetCurrentRegionMapSectionId());
    if (override == NULL || override->nickname == NULL || override->ivPool == IV_POOL_NONE)
        return FALSE;
    return FindIvPoolChoices(mon, override, GetLegalIvTable(override), &filter) != 0;
}

// Sets the met data of a Pokemon caught in battle (see src/data/overrides.h).
void SetCaughtMonMetData(struct Pokemon *mon)
{
    u16 species = GetMonData(mon, MON_DATA_SPECIES, NULL);
    metloc_u8_t metLocation = GetCurrentRegionMapSectionId();
    u8 metLevel;

    if (!IsCaughtMonMetAt(species))
    {
        u8 friendship = 120; // Hatched eggs always have friendship 120

        metLevel = 0; // Met level 0 displays as "hatched at" on summary screen
        SetMonData(mon, MON_DATA_MET_LOCATION, &metLocation);
        SetMonData(mon, MON_DATA_MET_LEVEL, &metLevel);
        SetMonData(mon, MON_DATA_FRIENDSHIP, &friendship);
    }
    else
    {
        // CreateBoxMon leaves met level 0, so this must always be set or they'd show as hatched.
        metLevel = GetMonData(mon, MON_DATA_LEVEL, NULL);
        SetMonData(mon, MON_DATA_MET_LOCATION, &metLocation);
        SetMonData(mon, MON_DATA_MET_LEVEL, &metLevel);
        TryApplyMetDataOverride(mon, species, metLocation);
    }
}

// Gives a Pokemon that is marked "met at" but could have come from an egg (see IsCaughtAsHatched)
// "hatched at" met data at its existing met location. Skips mons already hatched (metLevel == 0).
void TrySetHatchedMet(struct Pokemon *mon)
{
    u16 species = GetMonData(mon, MON_DATA_SPECIES, NULL);
    u8 metLevel = GetMonData(mon, MON_DATA_MET_LEVEL, NULL);

    if (metLevel == 0 || !IsCaughtAsHatched(species))
        return;

    metLevel = 0;
    SetMonData(mon, MON_DATA_MET_LEVEL, &metLevel);
}

