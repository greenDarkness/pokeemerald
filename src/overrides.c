void GiveOddEgg(void)
{
    u32 speciesIdx = Random() % ARRAY_COUNT(sWishEggSpecies);
    u16 species = sWishEggSpecies[speciesIdx];
    const struct PidIvPair *entry = &sWishEggPidIvs[Random() % WISH_EGG_PID_IV_EGG_COUNT];
    struct Pokemon mon;
    u8 isEgg;
    u8 metLevel;
    u16 ball;
    u8 language;
    u8 metLocation;
    u16 move;
    u8 pp;
    u8 i;

    CreateMon(&mon, species, EGG_HATCH_LEVEL, 0, TRUE, entry->pid, OT_ID_PLAYER_ID, 0);
    SetMonPidIvs(&mon, entry);

    // Overwrite moves with PCNY Wish Egg event moves
    for (i = 0; i < MAX_MON_MOVES; i++)
    {
        move = (i < ARRAY_COUNT(sWishEggMoves[speciesIdx])) ? sWishEggMoves[speciesIdx][i] : MOVE_NONE;
        pp = (move != MOVE_NONE) ? gBattleMoves[move].pp : 0;
        SetMonData(&mon, MON_DATA_MOVE1 + i, &move);
        SetMonData(&mon, MON_DATA_PP1 + i, &pp);
    }

    // Set egg properties (replicating CreateEgg)
    metLevel = 0;
    ball = ITEM_POKE_BALL;
    language = LANGUAGE_JAPANESE;
    metLocation = METLOC_SPECIAL_EGG;
    isEgg = TRUE;
    SetMonData(&mon, MON_DATA_POKEBALL, &ball);
    SetMonData(&mon, MON_DATA_NICKNAME, sJPEggNickname);
    SetMonData(&mon, MON_DATA_FRIENDSHIP, &gSpeciesInfo[species].eggCycles);
    SetMonData(&mon, MON_DATA_MET_LEVEL, &metLevel);
    SetMonData(&mon, MON_DATA_LANGUAGE, &language);
    SetMonData(&mon, MON_DATA_MET_LOCATION, &metLocation);
    SetMonData(&mon, MON_DATA_MODERN_FATEFUL_ENCOUNTER, &isEgg); // reuse TRUE
    SetMonData(&mon, MON_DATA_IS_EGG, &isEgg);

    if (GetMonData(&gEggSlot, MON_DATA_SPECIES) == SPECIES_NONE)
    {
        gEggSlot = mon;
        return;
    }
    GiveMonToPlayer(&mon);
}

// For hatched fateful encounter Pokemon (wish eggs), attempt to find a Method 2 PID
// from the wish egg PID/IV table that matches the desired nature, ability, and gender.
// Updates PID, IVs, and recalculates stats if a match is found.
bool8 TryReassignFatefulPid(struct Pokemon *mon, u8 nature, u8 abilityNum, u8 gender)
{
    u16 species;
    u32 otId;
    bool8 isShiny;
    u32 i, matchCount;
    const struct PidIvPair *match;

    if (GetMonData(mon, MON_DATA_IS_EGG, NULL))
        return FALSE;
    if (!GetMonData(mon, MON_DATA_MODERN_FATEFUL_ENCOUNTER, NULL))
        return FALSE;

    species = GetMonData(mon, MON_DATA_SPECIES, NULL);
    otId = GetMonData(mon, MON_DATA_OT_ID, NULL);
    isShiny = IsMonShiny(mon);

    // Reservoir sampling: pick uniformly at random from all matching entries
    matchCount = 0;
    match = NULL;
    for (i = 0; i < ARRAY_COUNT(sWishEggPidIvs); i++)
    {
        u32 pid = sWishEggPidIvs[i].pid;

        if ((pid % 25) != nature)
            continue;
        if ((pid & 1) != abilityNum)
            continue;
        if (GetGenderFromSpeciesAndPersonality(species, pid) != gender)
            continue;
        if (isShiny != IsShinyOtIdPersonality(otId, pid))
            continue;

        matchCount++;
        if ((Random() % matchCount) == 0)
            match = &sWishEggPidIvs[i];
    }

    if (match == NULL)
        return FALSE;

    SetMonPidIvs(mon, match);
    return TRUE;
}
