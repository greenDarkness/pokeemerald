"""Light the glass of a region's door metatiles (run after glass.py, which leaves doors alone).

    python doorglass.py kanto            # report doors with glass
    python doorglass.py kanto --apply

Sliding glass doors (DOOR_SOUND_SLIDING) get the PC/Mart look: a blue band over the top third of the glass and
warm light below. Other doors (window in the door) get warm light that keeps the glass shading.

Door animations are looked up by metatile id, so a primary door metatile can't simply be replaced by a lit copy.
The copy is added to each secondary tileset whose maps use the door, the maps are repointed, and
src/data/lit_door_metatiles.h tells field_door.c which original door each copy stands for.
"""
import argparse
import re
import struct
from collections import defaultdict

import glass
from glass import N, TS, MAPS, BYNAME, blocks, tile_px, append_metatile, attr_of, ramp, night_for, is_glass_color
from lighter import Lighter

FIELD_DOOR = N.rpath('src/field_door.c')
HEADER = N.rpath('src/data/lit_door_metatiles.h')
BLUE = (80, 160, 248)
# Solid painted doors whose blue the glass detector mistakes for glass (only the opening behind them is lit,
# by the door animation overlay): Cerulean houses / Bill's house / Route 5 Day Care, Vermilion houses,
# Cinnabar lab
EXCLUDE = {('gTileset_CeruleanCity', 0x298), ('gTileset_VermilionCity', 0x29e), ('gTileset_CinnabarIsland', 0x2ad),
           ('gTileset_SeviiIslands45', 0x2b9)}  # Four Island Day Care
# Glass doors to give the PC/Mart look (blue top band) though their animation isn't a sliding one, and the other
# halves of double doors (only one half is the door metatile): One Island's Network Center
SLIDING_LOOK = {('gTileset_SeviiIslands123', 0x2eb), ('gTileset_SeviiIslands123', 0x2ec)}


def door_table(region):
    """{metatile id: (label, sliding)} from the door table field_door.c uses in the region."""
    src = open(FIELD_DOOR, encoding='utf-8').read()
    name = 'sKantoDoorAnimGraphicsTable' if region in ('kanto', 'sevii') else 'sDoorAnimGraphicsTable'
    body = src[src.index(name + '[] ='):]
    body = body[:body.index('};')]
    labels = {k: int(v, 16) for k, v in re.findall(r'#define (METATILE_\w+)\s+(0x[0-9A-Fa-f]+)',
                                                   N.read_text('include/constants/metatile_labels.h'))}
    out = {}
    for lab, sound in re.findall(r'\{\s*(METATILE_\w+),\s*(DOOR_SOUND_\w+)', body):
        if lab in labels:
            out.setdefault(labels[lab], []).append((lab, sound == 'DOOR_SOUND_SLIDING'))
    return out


def owner_ok(label, gid, sec):
    """Secondary door labels name their tileset (METATILE_<Tileset>_...)."""
    return gid < 512 or label.split('_')[1] == sec.replace('gTileset_', '')


def find_doors(region):
    secs = N.mapsec_regions()
    N.assign_regions(MAPS, secs)
    table = door_table(region)
    owned = glass.owned_secondaries(region)
    hits = defaultdict(set)   # (sec, gid) -> {map}
    sliding = {}
    for m in MAPS.values():
        lay = m['_layout']
        if not lay or m.get('map_type') not in N.NATURAL_LIGHT_TYPES or N.region_of(m, secs) != region:
            continue
        sec = lay['secondary_tileset']
        if sec not in owned:
            continue
        for row in blocks(m['_name']):
            for g in row:
                for lab, sl in table.get(g, ()):
                    if owner_ok(lab, g, sec):
                        hits[(sec, g)].add(m['_name'])
                        sliding[(sec, g)] = sl
                if (sec, g) in SLIDING_LOOK:
                    hits[(sec, g)].add(m['_name'])
                    sliding[(sec, g)] = True
    return hits, sliding


def glass_pixels(L, gid):
    """Visible glass pixels (x, y) of a door metatile and their day colors."""
    G, S = L.gen, L.ts
    e = (G if gid < 512 else S).entries(gid)
    out = {}
    for y in range(16):
        for x in range(16):
            q = (y // 8) * 2 + (x // 8)
            for k in (4 + q, q):
                t, hf, vf, P = e[k]
                if k >= 4 and not t:
                    continue
                c = tile_px(G, S, t)[7 - (y % 8) if vf else y % 8][7 - (x % 8) if hf else x % 8]
                if k >= 4 and not c:
                    continue
                col = tuple((G if P < 6 else S).pal(P)[c])
                if is_glass_color(col):
                    out[(x, y)] = col
                break
    return out


def write_header(region_secs, copies):
    old = []
    try:
        for line in open(HEADER, encoding='utf-8'):
            m = re.match(r'\s*\{&(\w+), (0x\w+), (0x\w+)\},', line)
            if m and m.group(1) not in region_secs:
                old.append((m.group(1), int(m.group(2), 16), int(m.group(3), 16)))
    except FileNotFoundError:
        pass
    rows = sorted(set(old) | set(copies))
    lines = ['// Generated by tech/lighting/doorglass.py. Lit copies of primary door metatiles in secondary tilesets:',
             '// field_door.c looks up a copy\'s door animation (and night overlay) under the original metatile.', '']
    lines += [f'extern const struct Tileset {s};' for s in sorted({r[0] for r in rows})]
    lines += ['', 'static const struct LitDoorCopy sLitDoorCopies[] =', '{']
    lines += [f'    {{&{s}, 0x{c:03X}, 0x{o:03X}}},' for s, c, o in rows]
    lines += ['    {0},', '};', '']
    open(HEADER, 'w', newline='\n').write('\n'.join(lines))


def apply(region, report_only=False):
    hits, sliding = find_doors(region)
    copies = []
    by_sec = defaultdict(list)
    for (sec, gid), maps in hits.items():
        by_sec[sec].append((gid, maps))
    for sec, items in sorted(by_sec.items()):
        L = Lighter(sec)
        S = L.ts
        new_ids = {}
        for gid, maps in sorted(items):
            if (sec, gid) in EXCLUDE:
                continue
            px = glass_pixels(L, gid)
            if not px:
                continue
            ys = sorted({y for _, y in px})
            band = ys[0] + max(1, (ys[-1] - ys[0] + 1) // 3)
            nights = ramp(set(px.values()))

            def night(x, y, c, px=px, band=band, sl=sliding[(sec, gid)]):
                if (x, y) not in px:
                    return None
                return BLUE if sl and y < band else nights[px[(x, y)]]
            kind = 'sliding' if sliding[(sec, gid)] else 'window'
            if report_only:
                print(f'  {sec} {hex(gid)} {kind}: {len(px)} glass px, maps {sorted(maps)[:3]}')
                continue
            target = gid
            if gid < 512:
                target = append_metatile(S, L.gen.entries(gid), attr_of(L.gen, gid))
                new_ids[gid] = target
                copies.append((sec, target, gid))
            idx = {c for c in range(16)}  # glow_overlay filters by visible pixels below
            n = 0
            try:
                n = L.glow_overlay(target, list(px), idx, night=night)
            except (RuntimeError, AssertionError) as ex:
                if gid >= 512:  # edit the drawn tiles in place instead, one call per night color
                    groups = defaultdict(list)
                    for (x, y) in px:
                        groups[night(x, y, None)].append((x, y))

                    class Const(dict):
                        def __init__(self, v):
                            super().__init__()
                            self.v = v

                        def get(self, k, d=None):
                            return self.v
                    try:
                        for nc, pts in groups.items():
                            n += L.glow(target, pts, night=Const(nc))
                        print(f'  {sec} {hex(gid)} {kind}: {n} px (in place)')
                        continue
                    except RuntimeError as ex2:
                        ex = ex2
                print(f'  skip {sec} {hex(gid)}: {ex}')
                if gid < 512:  # drop the unused copy
                    S.mt = S.mt[:-16]
                    a = bytearray(open(S.attr_path, 'rb').read())[:-2]
                    open(S.attr_path, 'wb').write(bytes(a))
                    del new_ids[gid]
                    copies.pop()
                continue
            print(f'  {sec} {hex(gid)} -> {hex(target)} {kind}: {n} px')
        if report_only:
            continue
        L.save()
        for mn in sorted({m for _, ms in items for m in ms} | {m['_name'] for m in MAPS.values()
                                                             if m['_layout'] and m['_layout']['secondary_tileset'] == sec}):
            p = N.rpath(BYNAME[mn]['_layout']['blockdata_filepath'])
            b = bytearray(open(p, 'rb').read())
            changed = False
            for o in range(0, len(b) - 1, 2):
                v = struct.unpack('<H', b[o:o + 2])[0]
                if (v & 0x3FF) in new_ids:
                    b[o:o + 2] = struct.pack('<H', (v & ~0x3FF) | new_ids[v & 0x3FF])
                    changed = True
            if changed:
                open(p, 'wb').write(bytes(b))
    if not report_only:
        write_header(set(by_sec), copies)
        print(f'{len(copies)} primary door copies -> {HEADER}')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('region')
    ap.add_argument('--apply', action='store_true')
    a = ap.parse_args()
    apply(a.region, report_only=not a.apply)
